h("Q2: Your BST worst case is O(n). When does this happen?"),
p("Answer: When all serial numbers are inserted in alphabetical order (e.g., SN-001, SN-002, SN-003...)."),
p("Each new node becomes the right child of the previous one — the tree degenerates into a list."),
p("Height becomes n (not log n), so search is O(n) not O(log n)."),
p("In practice, serial numbers like 'MB-PRO-2024-XYZ', 'SM-G998B-123' are not sorted"),
p2("— they're random strings. The BST stays approximately balanced: O(log n) in practice."),
p("To guarantee O(log n): use a self-balancing tree (AVL or Red-Black) — outside course scope."),
h("Q3: Why did you choose Merge Sort instead of Quick Sort?"),
p("Answer: Merge Sort guarantees O(n log n) in ALL cases (best, average, worst)."),
p("Quick Sort is O(n log n) average but degrades to O(n²) with bad pivot choice"),
p2("(e.g., always picking first element as pivot on already-sorted data)."),
p("For a production asset management system, predictable performance is critical."),
p("One O(n²) sort during a demo on sorted data would be embarrassing."),
h("Q4: How does the Greedy algorithm guarantee the optimal schedule?"),
p("Answer: Two conditions for greedy correctness: (1) Greedy Choice Property and (2) Optimal Substructure."),
p("Greedy Choice: selecting the highest-urgency task first minimizes the maximum waiting time"),
p2("for critical tasks globally, not just locally."),
p("Optimal Substructure: the optimal schedule for the remaining tasks after removing"),
p2("the first task is independent of which task we selected first."),
p("This is equivalent to the 'Earliest Deadline First' scheduling algorithm, proven optimal."),
h("Q5: Why use BFS for shortest path and not DFS?"),
p("Answer: DFS explores as deep as possible first — it can find A PATH but not the SHORTEST path."),
p("Example: DFS from Main Gate to Lab Block might go Main Gate→Library→College of Computing→Lab Block (3 hops)"),
p2("instead of Main Gate→Admin Block→Lab Block (2 hops — the shortest)."),
p("BFS explores level by level using a queue. It always finds the minimum-hop path first."),
p("In an unweighted graph (all edges have equal cost), BFS shortest path = minimum hops."),
h("Q6: What happens if two assets have the same serial number in the BST?"),
