# make_plain_ppt.py — plain white PPT, text only, maximum detail
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

prs = Presentation()
prs.slide_width  = Inches(13.33)
prs.slide_height = Inches(7.5)
BLANK = prs.slide_layouts[6]

BLACK  = RGBColor(0x00,0x00,0x00)
GRAY   = RGBColor(0x44,0x44,0x44)
LGRAY  = RGBColor(0x88,0x88,0x88)
WHITE  = RGBColor(0xFF,0xFF,0xFF)
DBLUE  = RGBColor(0x00,0x33,0x88)

def slide():
    sl = prs.slides.add_slide(BLANK)
    bg = sl.background.fill
    bg.solid()
    bg.fore_color.rgb = WHITE
    return sl

def T(sl, text, x, y, w, h, size=13, bold=False,
      color=BLACK, align=PP_ALIGN.LEFT, italic=False):
    tb = sl.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tb.word_wrap = True
    tf = tb.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    r.font.color.rgb = color
    return tb

def title(sl, t):
    T(sl, t, 0.3, 0.12, 12.7, 0.65, size=26, bold=True, color=DBLUE)
    # underline rule
    from pptx.util import Inches, Pt, Emu
    ln = sl.shapes.add_shape(1, Inches(0.3), Inches(0.82), Inches(12.7), Pt(2))
    ln.fill.solid(); ln.fill.fore_color.rgb = DBLUE
    ln.line.fill.background()

def body(sl, lines, x=0.35, y=0.98, w=12.6, lh=0.34, base=13):
    """
    lines: list of (indent, text, size, bold, italic)
    indent 0 = normal, 1 = one level, 2 = two levels
    """
    cy = y
    for (ind, txt, sz, bld, itl) in lines:
        ix = x + ind*0.45
        iw = w - ind*0.45
        T(sl, txt, ix, cy, iw, lh+0.05, size=sz,
          bold=bld, italic=itl, color=BLACK if not bld else DBLUE if ind==0 and bld else BLACK)
        cy += lh * (sz/base)
    return cy

# short helper to make a line tuple
def h(text, sz=14, ind=0):   return (ind, text, sz, True,  False)
def p(text, sz=13, ind=1):   return (ind, text, sz, False, False)
def p2(text, sz=12, ind=2):  return (ind, text, sz, False, False)
def it(text, sz=12, ind=1):  return (ind, text, sz, False, True)
def code(text, sz=11, ind=1):return (ind, text, sz, False, True)

